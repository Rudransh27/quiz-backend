#!/usr/bin/env node
// scripts/sync-validators.js
//
// Generates src/validators/xbrlValidators.js — the server's single source of
// truth for code-card grading — from the frontend's original
// xbrl-quiz-app/src/utils/validators.js (browser code, kept in the repo only
// as the reference the parity test runs against; it is no longer bundled).
//
// The transform is purely mechanical: `export function` → `function`, a
// require of the DOM shim prepended, and a module.exports block appended. The
// validator bodies are copied byte-for-byte, so the server applies exactly
// the rules learners were graded by in the browser.
//
// Usage:  node scripts/sync-validators.js [path/to/validators.js]
const fs = require('fs');
const path = require('path');

const DEFAULT_SOURCE = path.join(__dirname, '..', '..', 'xbrl-quiz-app', 'src', 'utils', 'validators.js');
const TARGET = path.join(__dirname, '..', 'src', 'validators', 'xbrlValidators.js');

function generate(text) {
  const names = [...text.matchAll(/^export function (\w+)\s*\(/gm)].map((m) => m[1]);
  if (!names.length) throw new Error('No "export function" declarations found.');
  if (/^export\s+(?!function\b)/m.test(text)) {
    throw new Error('Unsupported export form found (only "export function name(" is handled).');
  }
  const body = text.replace(/^export function /gm, 'function ');
  return {
    names,
    code: [
      '// src/validators/xbrlValidators.js',
      '// GENERATED by scripts/sync-validators.js — do not edit by hand.',
      `// Source: xbrl-quiz-app/src/utils/validators.js (${names.length} validators)`,
      '/* eslint-disable */',
      "const { DOMParser, XPathResult } = require('./domShim');",
      '// The browser source has debug console.log calls that dump whole DOM trees;',
      '// silence just console.log inside this module (warn/error still go out).',
      'const console = { ...globalThis.console, log() {} };',
      '',
      body.trimEnd(),
      '',
      `module.exports = {\n${names.map((n) => `  ${n},`).join('\n')}\n};`,
      '',
    ].join('\n'),
  };
}

if (require.main === module) {
  const source = path.resolve(process.argv[2] || DEFAULT_SOURCE);
  try {
    const { names, code } = generate(fs.readFileSync(source, 'utf8'));
    fs.writeFileSync(TARGET, code, 'utf8');
    console.log(`Wrote ${path.relative(process.cwd(), TARGET)} with ${names.length} validators.`);
  } catch (err) {
    console.error(`${source}: ${err.message}`);
    process.exit(1);
  }
}

module.exports = { generate, DEFAULT_SOURCE, TARGET };
